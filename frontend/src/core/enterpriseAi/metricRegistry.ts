const BY_ID = new Map(METRICS.map((metric) => [metric.id, metric]));

export function listMetrics(): readonly MetricDefinition[] {
  return METRICS;
}

export function getMetric(id: string): MetricDefinition | undefined {
  return BY_ID.get(id);
}

export function requireMetric(id: string): MetricDefinition {
  const metric = BY_ID.get(id);
  if (!metric) throw new Error(`Unknown enterprise AI metric: ${id}`);
  return metric;
}

export function metricsByDomain(domain: MetricDefinition['owningDomain']): MetricDefinition[] {
  return METRICS.filter((metric) => metric.owningDomain === domain);
}

export function resolveMetric(id: string, ctx: MetricSourceContext): number | null {
  return requireMetric(id).sourceFn(ctx);
}

export function listOwningDomains(): MetricDefinition['owningDomain'][] {
  return [...new Set(METRICS.map((metric) => metric.owningDomain))];
}
