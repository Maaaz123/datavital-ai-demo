function finalizeTargets(seeds: TargetSeed[]): EmployeeTarget[] {
  return seeds.map((s) => {
    const achievement_pct = calculateTargetAchievement(s.target_value, s.actual_value, s.direction);
    return {
      ...s,
      achievement_pct,
      status: performanceStatusFromAchievement(achievement_pct),
    };
  });
}

