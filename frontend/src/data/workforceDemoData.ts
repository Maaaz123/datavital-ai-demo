function employeeFromSeed(seed: SeedEmployee): Employee {
  const targets = DEMO_TARGETS.filter((t) => t.employee_id === seed.id);
  const overall = calculateWeightedAchievement(targets);
  return {
    ...seed,
    overall_achievement_pct: overall,
    performance_status: performanceStatusFromAchievement(overall),
    data_status: seed.last_performance_review ? 'available' : 'partial',
  };
}

